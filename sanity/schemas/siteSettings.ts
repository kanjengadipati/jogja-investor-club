import { defineType, defineField } from 'sanity';

export const siteSettingsSchema = defineType({
  name: 'siteSettings',
  title: 'Pengaturan Situs',
  type: 'document',
  // Singleton — hanya ada satu dokumen ini
  groups: [
    { name: 'general', title: 'Umum', default: true },
    { name: 'sections', title: '📋 Visibilitas Section' },
  ],
  fields: [
    defineField({
      name: 'brandName',
      title: 'Nama Brand',
      type: 'string',
      description: 'Contoh: Jogja Investor',
      group: 'general',
    }),
    defineField({
      name: 'brandSuffix',
      title: 'Nama Brand (bagian kedua)',
      type: 'string',
      description: 'Contoh: Club',
      group: 'general',
    }),
    defineField({
      name: 'whatsappNumber',
      title: 'Nomor WhatsApp',
      type: 'string',
      description: 'Format: 628xxxxxxxxxx (tanpa + atau spasi)',
      group: 'general',
    }),
    defineField({
      name: 'address',
      title: 'Alamat',
      type: 'string',
      group: 'general',
    }),
    defineField({
      name: 'tagline',
      title: 'Tagline Footer',
      type: 'string',
      group: 'general',
    }),
    defineField({
      name: 'defaultWhatsAppMessage',
      title: 'Pesan WhatsApp Default',
      type: 'text',
      rows: 3,
      group: 'general',
    }),
    defineField({
      name: 'logo',
      title: 'Logo',
      type: 'image',
      options: { hotspot: true },
      group: 'general',
    }),

    // ─── Section Visibility ────────────────────────────────────────────────
    defineField({
      name: 'showSectionHero',
      title: 'Tampilkan Hero',
      type: 'boolean',
      description: 'Section pembuka utama halaman.',
      initialValue: true,
      group: 'sections',
    }),
    defineField({
      name: 'showSectionPropertyArchetypes',
      title: 'Tampilkan Solusi Properti',
      type: 'boolean',
      description: 'Kartu tipe properti (Kos, Villa, Rumah, dst).',
      initialValue: true,
      group: 'sections',
    }),
    defineField({
      name: 'showSectionStrategicAreas',
      title: 'Tampilkan Area Strategis (Peta GIS)',
      type: 'boolean',
      description: 'Peta interaktif area & cluster investasi.',
      initialValue: true,
      group: 'sections',
    }),
    defineField({
      name: 'showSectionProcessSteps',
      title: 'Tampilkan Proses Layanan',
      type: 'boolean',
      description: 'Langkah-langkah proses kerjasama.',
      initialValue: true,
      group: 'sections',
    }),
    defineField({
      name: 'showSectionProjects',
      title: 'Tampilkan Portofolio Proyek',
      type: 'boolean',
      description: 'Daftar proyek yang telah selesai.',
      initialValue: true,
      group: 'sections',
    }),
    defineField({
      name: 'showSectionTestimonials',
      title: 'Tampilkan Testimoni',
      type: 'boolean',
      description: 'Ulasan dari klien & investor.',
      initialValue: true,
      group: 'sections',
    }),
    defineField({
      name: 'showSectionFAQ',
      title: 'Tampilkan FAQ',
      type: 'boolean',
      description: 'Pertanyaan yang sering diajukan.',
      initialValue: true,
      group: 'sections',
    }),
    defineField({
      name: 'showSectionCalculator',
      title: 'Tampilkan Kalkulator Potensi',
      type: 'boolean',
      description: 'Kalkulator estimasi ROI & potensi lahan.',
      initialValue: true,
      group: 'sections',
    }),
  ],
  preview: {
    select: { title: 'brandName' },
    prepare: ({ title }) => ({ title: `Pengaturan: ${title}` }),
  },
});
